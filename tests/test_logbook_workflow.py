    def test_leader_only_progress_and_sequential_packages(self):
        self.login('JB', 'Ranger')
        self.page.evaluate('observerTasks()')
        self.page.locator('.obsCategory summary').first.click()
        expect(self.page.locator('.obsTask input').first).to_be_disabled()
        expect(self.page.locator('[data-package=A] input')).to_be_disabled()
        before = self.state()
        self.page.evaluate("() => {const p=session.id;toggleObsTask(p,Object.values(db.observerTasks).flat()[0].id,true);toggleBonus(p,'A',true);toggleStageTaskV19('Erkunder',p,db.growthTasks.Erkunder[0].id,true)}")
        self.assertEqual(self.state(), before)
        self.nav('Benutzer wechseln')
        self.login('DL', 'Leiter')
        self.page.evaluate("observerTasks(db.rangers.find(p=>p.name==='JB').id)")
        expect(self.page.locator('[data-package=A] input')).to_be_enabled()
        expect(self.page.locator('[data-package=B] input')).to_be_disabled()
        self.page.evaluate("toggleBonus(db.rangers.find(p=>p.name==='JB').id,'C',true)")
        expect(self.page.locator('[data-package=C] input')).not_to_be_checked()
        for key in ['A', 'B', 'C', 'R']:
            self.page.locator(f'[data-package={key}] input').check()
        self.page.locator('.obsCategory summary').first.click()
        self.page.locator('.obsTask input').first.check()
        self.assertEqual(self.page.evaluate("observerCounts(db.rangers.find(p=>p.name==='JB').id).bcount"), 4)
        self.page.locator('[data-package=A] input').uncheck()
        self.assertEqual(self.page.evaluate("observerCounts(db.rangers.find(p=>p.name==='JB').id).bcount"), 0)
        self.assertTrue(self.page.evaluate("Object.values(db.observerBonus[db.rangers.find(p=>p.name==='JB').id]).every(v=>!v)"))
        self.reload(role='Leiter')
        self.page.evaluate("observerTasks(db.rangers.find(p=>p.name==='JB').id)")
        expect(self.page.locator('[data-package=B] input')).to_be_disabled()

    def test_stammleiter_adds_categorized_task_and_ranger_cannot(self):
        self.login('PM', 'Stammleiter')
        original = self.page.evaluate('db.growthTasks.Forscher')
        self.page.evaluate("growthTaskFormV16('Forscher')")
        category = self.page.locator('#box select[name=category]')
        expect(category).to_have_attribute('required', '')
        self.page.locator('#box input[name=title]').fill('Neue Forscheraufgabe')
        self.page.get_by_role('button', name='Speichern', exact=True).click()
        expect(self.page.locator('#growth-task-form')).to_be_visible()
        category.select_option('__new__')
        self.page.get_by_role('textbox', name='Neue Kategorie', exact=True).fill('Natur erleben')
        self.page.get_by_role('button', name='Speichern', exact=True).click()
        expect(self.page.locator('#box')).to_contain_text('Natur erleben')
        self.page.locator('#box').get_by_role('button', name='Schließen', exact=True).click()
        self.reload(role='Stammleiter')
        after = self.page.evaluate('db.growthTasks.Forscher')
        self.assertEqual(after[:-1], original)
        self.assertEqual(after[-1]['category'], 'Natur erleben')
        self.page.evaluate('RangerHub.editObserverTask()')
        self.page.locator('#box select[name=category]').select_option(index=1)
        self.page.locator('#box input[name=title]').fill('Neue Beobachteraufgabe')
        self.page.get_by_role('button', name='Speichern', exact=True).click()
        self.assertTrue(self.page.evaluate("Object.values(db.observerTasks).flat().some(t=>t.title==='Neue Beobachteraufgabe')"))
        self.nav('Benutzer wechseln')
        self.login('JB', 'Ranger')
        self.page.evaluate("growthTaskFormV16('Forscher');RangerHub.editObserverTask()")
        self.assertFalse(self.page.evaluate("modal.classList.contains('show')"))

    def test_annual_vision_per_year_and_tribe_appears_in_meetings(self):
        self.login('DL', 'Leiter')
        self.nav('Leitermeetings')
        self.page.get_by_role('button', name='Jahresvision und Ziele hinterlegen').click()
        self.page.locator('#box textarea[name=vision]').fill('Gemeinsam mutig wachsen')
        self.page.locator('#box textarea[name=goals]').fill('Drei Fahrten\nNeue Leiter begleiten')
        self.page.get_by_role('button', name='Jahresplanung speichern').click()
        expect(self.page.locator('[data-annual-plan]')).to_contain_text('Gemeinsam mutig wachsen')
        self.page.evaluate('openLeaderMeeting(200)')
        expect(self.page.locator('#box [data-annual-plan]')).to_contain_text('Drei Fahrten')
        self.page.locator('#box').get_by_role('button', name='Schließen', exact=True).click()
        self.page.evaluate("leaderForm(0,'2026-12-01')")
        expect(self.page.locator('#box [data-annual-plan]')).to_contain_text('Gemeinsam mutig wachsen')
        self.page.locator('#box input[name=date]').fill('2027-01-01')
        self.page.locator('#box input[name=date]').dispatch_event('change')
        expect(self.page.locator('#box [data-annual-plan]')).not_to_contain_text('Gemeinsam mutig wachsen')
        self.page.evaluate('closeM()')
        self.reload(role='Leiter')
        self.page.evaluate('openLeaderMeeting(200)')
        expect(self.page.locator('#box [data-annual-plan]')).to_contain_text('Neue Leiter begleiten')
        self.page.evaluate('closeM()')
        self.nav('Benutzer wechseln')
        self.login()
        self.page.locator('#v24-stamm-switch').select_option('meppen')
        self.nav('Leitermeetings')
        expect(self.page.locator('#main [data-annual-plan]')).not_to_contain_text('Gemeinsam mutig wachsen')

