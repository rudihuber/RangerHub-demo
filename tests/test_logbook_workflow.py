        self.page.wait_for_function('RangerHub.logbookReady')
        self.assertTrue(self.page.evaluate("o=>db.rangers.some(r=>r.id===o.r&&r.name==='JB')&&db.leaders.some(l=>l.id===o.l&&l.name==='PM')&&db.stageProgress[o.r].Forscher[o.t]", original))
        self.assertTrue(self.page.evaluate("db.growthTasks.Forscher.some(t=>t.id===1234567&&t.description==='Erhalten')"))
        self.assertTrue(self.page.evaluate("!db.rangers.some(p=>p.id===9909)&&db.archivedRangers.some(p=>p.id===9909)&&db.observerBonus[9909].A"))
        self.assertEqual(self.page.evaluate('db.rangers.length'), 8)
