    def test_migration_preserves_ids_custom_tasks_and_existing_progress(self):
        self.login()
        original = self.page.evaluate("() => {const r=db.rangers.find(p=>p.name==='JB');r.name='Demo-Ranger 01';const l=db.leaders.find(p=>p.name==='PM');l.name='Demo-Stammleitung';const task=db.growthTasks.Forscher[0];db.stageProgress[r.id]={[ 'Forscher']:{[task.id]:true}};db.growthTasks.Forscher.push({id:1234567,category:'Eigene Kategorie',title:'Eigene Aufgabe',description:'Erhalten'});db.rangers.push({id:9909,name:'Demo-Ranger 09',idHint:'v23ex7',stage:'Beobachter'});db.observerBonus[9909]={A:true};delete v24Store.shared.demoProfileNames202611;v24Persist();return {r:r.id,l:l.id,t:task.id}}")
